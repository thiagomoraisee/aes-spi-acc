def hex2list(hex_data, nbytes=2):
    hex_data_list = []
    for i in range(int(len(hex_data)/nbytes)):
        hex_data_list.append(int(hex_data[2*i : 2*(i+1)], 16))
    return hex_data_list

def list2hex(hex_num_list, endianess = "big"):
    if endianess.lower() == "big":
        hex_num = hex_num_list.pop(0)
        while(len(hex_num_list) > 0):
            hex_num = (hex_num << 2*4) | hex_num_list.pop(0) # Shift left and or-combine

    elif endianess.lower() == "little":
        hex_num = hex_num_list.pop()
        while(len(hex_num_list) > 0):
            hex_num = (hex_num << 2*4) | hex_num_list.pop() # Shift left and or-combine
    else:
        raise ValueError(f"Invalid bit order: {endianess}-endian")

    return hex_num

def rcon(round):
    if round < 1:
        raise ValueError(f"Invalid round number {round}. Must be > 0.")
    elif round == 1:
        rc = 1
    else:
        rc = rcon(round-1)[0] # Extract round constant
        if rc < 0x80:
            rc = 2*rc
        else:
            rc = ((2*rc) ^ 0x11B ) % 0x100

    return [rc, 0, 0, 0]

def rot(hex_list, shift, dir="left"):
    if dir.lower() == "left":
        return hex_list[shift::] + hex_list[:shift]
    elif dir.lower() == "right":
        return hex_list[-shift:] + hex_list[:-shift]
    else:
        raise ValueError(f"Invalid direction: {dir}")

class AESCore:
    def __init__(self, key):
        self.key = hex2list(key)
        self.key_size_bits = 128
        self.num_round_keys = 11
        self.exp_key = []

    def key_expansion(self):
        N = int(self.key_size_bits/32) # Number of words of 32 bits per key
        for i in range(4*self.num_round_keys):
            if i < N:
                self.exp_key.append(self.key[4*i : 4*(i+1)])
            elif (i >= N) and (i % N == 0):
                rot_cons = rcon(i/N)
                rot_word = rot(self.exp_key[i-1], 1)
                exp_key_item = []
                for j in range(4):
                    lsb = 0x0F & rot_word[j]
                    msb = rot_word[j] >> 4
                    sub_word = SBOX[msb][lsb]
                    exp_key_item.append(self.exp_key[i-N][j] ^ sub_word ^ rot_cons[j])
                self.exp_key.append(exp_key_item)
            else:
                self.exp_key.append( [w1 ^ w2 for w1, w2 in zip(self.exp_key[i-N], self.exp_key[i-1])] )


