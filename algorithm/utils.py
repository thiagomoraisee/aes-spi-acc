def gfmult(num, coef):
    num &= 0xFF
    coef &= 0xFF
    res = 0

    for _ in range(8):
        if coef & 0x01:
            res ^= num

        msb_set = num & 0x80
        num = (num << 1) & 0xFF
        if msb_set:
            num ^= 0x1B

        coef >>= 1

    return res

def matview(matrix, llabels="", rlabels="", shift=0, format="02x", ljust="left"):

    N = len(matrix)    # Number of matrix lines
    M = len(matrix[0]) # Number of matrix columns

    if isinstance(llabels, list):
        just = max(len(tag) for tag in llabels) + shift
        if ljust.lower() == "left":
            left_labels = [l+(just - len(l))*" " for l in llabels]
        elif ljust.lower() == "right":
            left_labels = [(just - len(l))*" "+l for l in llabels]
        else:
            raise ValueError(f"Invalid Justification: {ljust}")
    else:
        if ljust.lower() == "left":
            left_labels = [llabels + shift*" " for l in range(N)]
        elif ljust.lower() == "right":
            left_labels = [shift*" " + llabels for l in range(N)]
        else:
            raise ValueError(f"Invalid Justification: {ljust}")

    if isinstance(rlabels, list):
        right_labels = [r for r in rlabels]
    else:
        right_labels = [rlabels for r in range(N)]

    for i in range(N):
        print(f"{left_labels[i]}", end=" ")
        for j in range(M):
            print(f"{matrix[i][j]:02x}", end=" ")
