def hex2list(hex_data, nbytes=2):
    hex_data_list = []
    for i in range(int(len(hex_data)/nbytes)):
        hex_data_list.append(int(hex_data[2*i : 2*(i+1)], 16))
    return hex_data_list

def list2hex(hex_num_list, endianess = "big"):
    hex_list = hex_num_list.copy()
    if endianess.lower() == "big":
        hex_num = hex_list.pop(0)
        while(len(hex_list) > 0):
            hex_num = (hex_num << 2*4) | hex_list.pop(0) # Shift left and or-combine

    elif endianess.lower() == "little":
        hex_num = hex_list.pop()
        while(len(hex_list) > 0):
            hex_num = (hex_num << 2*4) | hex_list.pop() # Shift left and or-combine
    else:
        raise ValueError(f"Invalid bit order: {endianess}-endian")

    return hex_num

def join(state_matrix):
    text = ""
    for line in state_matrix:
        text += f"{list2hex(line):08x}"
    return text

def rcon(round):
    if round < 1:
        raise ValueError(f"Invalid round number {round}. Must be > 0.")
    elif round == 1:
        rc = 1
    else:
        rc = rcon(round-1)[0] # Extract round constant
        if rc < 0x80:
            rc = 2*rc
        else:
            rc = ((2*rc) ^ 0x11B ) % 0x100

    return [rc, 0, 0, 0]

def rot(hex_list, shift, dir="left"):
    if dir.lower() == "left":
        return hex_list[shift::] + hex_list[:shift]
    elif dir.lower() == "right":
        return hex_list[-shift:] + hex_list[:-shift]
    else:
        raise ValueError(f"Invalid direction: {dir}")

def transpose(matrix):
    rows = len(matrix)       # Number of rows
    cols = len(matrix[0])    # Number of columns
    matrix_t = []
    
    for i in range(cols):
        row = []
        for j in range(rows):
            row.append(matrix[j][i])
        matrix_t.append(row)
        
    return matrix_t

